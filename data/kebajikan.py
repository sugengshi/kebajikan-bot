def get_mahir_virtues_for_day(day_number: int) -> list:
    """Returns 6 kebajikan IDs for the given day in the mahir rotation.

    Day 1: [1,2,3,4,5,6]
    Day 2: [7,8,9,10,1,2]
    Day 3: [3,4,5,6,7,8]
    Day 4: [9,10,1,2,3,4]
    Day 5: [5,6,7,8,9,10]
    Day 6+: repeats from Day 1
    """
    start = ((day_number - 1) * 6) % 10
    return [(start + i) % 10 + 1 for i in range(6)]


def get_kebajikan_by_id(kebajikan_id: int) -> dict:
    return KEBAJIKAN.get(kebajikan_id, {})

def get_all_kebajikan_list() -> list:
    """Return list of (id, nama, emoji) for selection menus."""
    return [(k_id, v["nama"], v["emoji"]) for k_id, v in KEBAJIKAN.items()]

def format_kebajikan_menu() -> str:
    """Format kebajikan list for display."""
    lines = []
    current_group = ""
    for k_id, data in KEBAJIKAN.items():
        if data["kelompok"] != current_group:
            current_group = data["kelompok"]
            lines.append(f"\n*{current_group}*")
        lines.append(f"{data['emoji']} {k_id}. {data['nama']}")
    return "\n".join(lines)
