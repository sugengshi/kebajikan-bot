# Advanced: 147-day cycle, 6 slots
ADV_STARTS   = [23, 48, 73, 98, 123, 6]
ADV_OVERRIDE = {23: 23, 24: 24, 25: 25}   # day → vow for slot 6 (index 5)
ADV_CYCLE    = 147
ADV_TIMES    = ["07:00", "09:30", "12:00", "14:30", "17:00", "19:30"]

# Super Advanced: 44-day cycle, 6 slots
SA_STARTS  = [1, 45, 89, 133, 177, 221]
SA_CYCLE   = 44
SA_TIMES   = ["07:00", "09:30", "12:00", "14:30", "17:00", "19:30"]


def get_adv_vows_for_day(day_number: int) -> list[int]:
    """Return list of 6 vow numbers for Advanced on a given day (1-indexed)."""
    d = ((day_number - 1) % ADV_CYCLE) + 1   # normalise to 1-147
    row = []
    for slot, s in enumerate(ADV_STARTS):
        v = ((s - 1 + (d - 1)) % ADV_CYCLE) + 1
        if slot == 5 and d in ADV_OVERRIDE:
            v = ADV_OVERRIDE[d]
        row.append(v)
    return row


def get_sa_vows_for_day(day_number: int) -> list:
    """Return list of 6 vow numbers for Super Advanced on a given day.
    On day 44 of each cycle, the last slot returns [264, 265] as a pair."""
    d = ((day_number - 1) % SA_CYCLE) + 1    # normalise to 1-44
    row = []
    for slot, s in enumerate(SA_STARTS):
        v = ((s - 1 + (d - 1)) % 265) + 1
        row.append(v)
    if d == SA_CYCLE:                         # day 44: last slot = both 264 & 265
        row[-1] = [264, 265]
    return row


def format_vow_message(vow_num: int, vow_dict: dict, level_label: str, lang: str = "id") -> str:
    """Format a single vow as a bilingual Telegram message."""
    from utils.i18n import T
    en, id_ = vow_dict.get(vow_num, ("Unknown vow", "Sumpah tidak dikenal"))
    vow_word = "Vow" if lang == "en" else "Sumpah"
    return (
        f"🪷 *{level_label}*\n"
        f"*{vow_word} #{vow_num}*\n\n"
        f"🇬🇧 _{en}_\n\n"
        f"🇮🇩 _{id_}_\n\n"
        f"─────────────────────\n"
        f"{T('sumpah_renungan', lang)}"
    )


def format_vow_pair_message(vow_nums: list, vow_dict: dict, level_label: str, lang: str = "id") -> str:
    """Format a pair of vows (used for SA day 44 last slot)."""
    from utils.i18n import T
    vow_word = "Vow" if lang == "en" else "Sumpah"
    lines = [f"🪷 *{level_label}*\n"]
    for n in vow_nums:
        en, id_ = vow_dict.get(n, ("Unknown vow", "Sumpah tidak dikenal"))
        lines.append(f"*{vow_word} #{n}*")
        lines.append(f"🇬🇧 _{en}_")
        lines.append(f"🇮🇩 _{id_}_\n")
    lines.append("─────────────────────")
    lines.append(T("sumpah_renungan", lang))
    return "\n".join(lines)


# ─── STARTING VOW → DAY BACK-CALCULATION ─────────────────────────────────────

def adv_vow_to_day(vow_num: int) -> int:
    """Given a starting vow number, return the day number to begin from.
    Advanced slot 1 starts at vow 23, cycle = 147 days.
    Example: vow 32 → day 10."""
    return (vow_num - ADV_STARTS[0]) % ADV_CYCLE + 1


def sa_vow_to_day(vow_num: int) -> int:
    """Given a starting vow number, return the day number to begin from.
    Super Advanced slot 1 starts at vow 1, cycle = 44 days.
    Example: vow 11 → day 11."""
    return (vow_num - SA_STARTS[0]) % SA_CYCLE + 1


